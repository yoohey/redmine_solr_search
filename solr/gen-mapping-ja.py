#!/usr/bin/env python3
"""Generate common/mapping-ja.txt (the MappingCharFilter table applied before ICU NFKC; see common/common-types.xml).

Run from this folder (solr/): python3 gen-mapping-ja.py > common/mapping-ja.txt
Kept outside common/, because everything in common/ is uploaded with the configsets.
Why each rule is there: docs/experiments/schema-v1/README.md, rounds 2 and 3c.

The ヴ row is NOT folded into the バ row (round 3c): the index keeps the spelling, so that a search can either tell
them apart or, when the plugin expands the query into both spellings, find both, without re-indexing. Should the
index ever fold it after all, put that table AFTER the NFKC char filter (a third char filter): before NFKC it misses
the decomposed ウ + U+3099 (round 3c, "fold2"). A rule added here applies at index time, so it needs a full re-index.
"""
import unicodedata

HEADER = """\
# redmine_solr_search: spelling variants unified before tokenising (both the n-gram and the morphological type).
# GENERATED by solr/gen-mapping-ja.py -- edit that script, not this file.
# Applied BEFORE the ICU NFKC char filter (common-types.xml). NFKC already turns half-width katakana into
# full-width, full-width letters and digits into ASCII, the ideographic space into a normal space, and circled
# ideographs into plain ones; only what NFKC gets wrong for highlighting goes here.
# The ヴ row is left as written on purpose (schema v1 round 3c; see gen-mapping-ja.py).
# Schema v1, rounds 2 and 3c (docs/experiments/schema-v1).
"""


def parenthesized_ideographs():
    """U+3220..U+3243 (㈠..㉃). NFKC expands them to three characters ("㈱" -> "(株)"), which leaves the ideograph
    with a zero-width offset, so the highlighter marks nothing. Map them one to one to the bare ideograph first."""
    for cp in range(0x3220, 0x3244):
        ch = chr(cp)
        nfkc = unicodedata.normalize("NFKC", ch)
        assert nfkc.startswith("(") and nfkc.endswith(")") and len(nfkc) == 3, (hex(cp), nfkc)
        yield ch, nfkc[1]


def main():
    print(HEADER)
    # (a rule line must hold nothing but the rule: MappingCharFilterFactory does not take trailing comments)
    print("# Parenthesized ideographs U+3220..U+3243 -> the ideograph (㈱ -> 株), one to one, so offsets stay right")
    for src, dst in parenthesized_ideographs():
        print(f'"{src}" => "{dst}"')


if __name__ == "__main__":
    main()
